"""
Generate the large digits-only readout font, firmware/components/gauge_render/fonts/
montserrat_digits_80.c, as an LVGL 9 lv_font_fmt_txt font (4 bpp, uncompressed, no kerning).

    python tools/fonts/make_digits_font.py

Why a generator here rather than lv_font_conv: it needs only Pillow, which the face and splash
tools already use, and the glyph set is tiny. Why digits only: the readout is read from the
driver's seat on the A-pillar, so it wants to be big, and a full 80 px Latin font would cost
~200 KB of flash (and PSRAM, since .rodata is copied there; ADR 0012). Readouts show a number,
so 0-9, '.', '-', '+' and space are all it needs. A face that puts letters in a readout set in this
font draws them blank, and the editor warns about it.

Source: Montserrat Medium, the font LVGL's built-in montserrat_* sizes are made from (SIL OFL 1.1),
from LVGL's own scripts/built_in_font/ in the managed component.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
TTF = ROOT / "firmware/managed_components/lvgl__lvgl/scripts/built_in_font/Montserrat-Medium.ttf"
OUT = ROOT / "firmware/components/gauge_render/fonts/montserrat_digits_80.c"
SIZE = 80
NAME = "montserrat_digits_80"
CHARS = " +-.0123456789"


def pack4(pixels):
    """8-bit coverage to 4 bpp, two pixels a byte, high nibble first, as one stream per glyph."""
    out = bytearray()
    nib = [(p + 8) // 17 for p in pixels]  # 0..255 -> 0..15, rounded
    for i in range(0, len(nib), 2):
        hi = nib[i]
        lo = nib[i + 1] if i + 1 < len(nib) else 0
        out.append((hi << 4) | lo)
    return out


def main():
    ttf = Path(sys.argv[1]) if len(sys.argv) > 1 else TTF
    font = ImageFont.truetype(str(ttf), SIZE)
    ascent, descent = font.getmetrics()

    bitmap = bytearray()
    glyphs = []  # (bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y)
    for ch in CHARS:
        adv_w = round(font.getlength(ch) * 16)
        if ch == " ":
            glyphs.append((0, adv_w, 0, 0, 0, 0))
            continue
        x0, y0, x1, y1 = font.getbbox(ch)  # relative to the pen at the top of the ascent
        ox, oy, w, h = x0, y0, x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = list(img.getdata())
        # Trim empty rows and columns so the box is tight.
        rows = [r for r in range(h) if any(px[r * w:(r + 1) * w])]
        cols = [c for c in range(w) if any(px[r * w + c] for r in range(h))]
        r0, r1, c0, c1 = rows[0], rows[-1], cols[0], cols[-1]
        bw, bh = c1 - c0 + 1, r1 - r0 + 1
        crop = [px[r * w + c] for r in range(r0, r1 + 1) for c in range(c0, c1 + 1)]
        top = oy + r0                       # from the top of the ascent
        ofs_y = ascent - (top + bh)         # LVGL: bottom of the box above the baseline
        glyphs.append((len(bitmap), adv_w, bw, bh, ox + c0, ofs_y))
        bitmap += pack4(crop)

    # Like lv_font_conv, the line spans the glyphs actually included, not the font's ascent and
    # descent: digits sit on the baseline, so the readout's box is no taller than a digit.
    inked = [g for g in glyphs if g[3] > 0]
    top = max(g[5] + g[3] for g in inked)
    bottom = min(g[5] for g in inked)
    line_height, base_line = top - bottom, -bottom

    lines = []
    w = lines.append
    w("/*")
    w(f" * {NAME}: Montserrat Medium, {SIZE} px, 4 bpp, glyphs \"{CHARS}\" only.")
    w(" * Generated by tools/fonts/make_digits_font.py; edit that, not this. Font: SIL OFL 1.1.")
    w(" */")
    w("")
    w('#include "lvgl.h"')
    w("")
    w("static const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        w("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 16]) + ",")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    w("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,")
    for ch, (bi, adv, bw, bh, ox, oy) in zip(CHARS, glyphs):
        w(f"    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, "
          f".ofs_x = {ox}, .ofs_y = {oy}}}, /* '{ch}' */")
    w("};")
    w("")
    # One FORMAT0_TINY range per run of consecutive code points.
    runs = []
    for i, ch in enumerate(CHARS):
        cp = ord(ch)
        if runs and runs[-1][0] + runs[-1][1] == cp:
            runs[-1][1] += 1
        else:
            runs.append([cp, 1, i + 1])
    w("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    for start, length, gid in runs:
        w(f"    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gid}, "
          ".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
          ".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
    w("};")
    w("")
    w("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    w("    .glyph_bitmap  = glyph_bitmap,")
    w("    .glyph_dsc     = glyph_dsc,")
    w("    .cmaps         = cmaps,")
    w("    .kern_dsc      = NULL,")
    w("    .kern_scale    = 0,")
    w(f"    .cmap_num      = {len(runs)},")
    w("    .bpp           = 4,")
    w("    .kern_classes  = 0,")
    w("    .bitmap_format = 0,")
    w("};")
    w("")
    w(f"const lv_font_t lv_font_{NAME} = {{")
    w("    .get_glyph_dsc       = lv_font_get_glyph_dsc_fmt_txt,")
    w("    .get_glyph_bitmap    = lv_font_get_bitmap_fmt_txt,")
    w(f"    .line_height         = {line_height},")
    w(f"    .base_line           = {base_line},")
    w("    .subpx               = LV_FONT_SUBPX_NONE,")
    w("    .underline_position  = -6,")
    w("    .underline_thickness = 4,")
    w("    .dsc                 = &font_dsc,")
    w("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(bitmap)} bytes of bitmap, line height {line_height}")


if __name__ == "__main__":
    main()
